// Converts docs/handbook/*.md into src/features/learn/handbook.generated.ts (HTML strings), so the handbook can be read inside the app.
// Our own trusted files only. Run: npm run handbook:build  (also runs before `npm run build`).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { marked } from "marked";

const dir = "docs/handbook";
const files = readdirSync(dir).filter((f) => /^\d\d-.*\.md$/.test(f)).sort();
const modules = files.map((f) => {
  const md = readFileSync(`${dir}/${f}`, "utf8");
  const title = (md.match(/^# (.+)$/m)?.[1] ?? f).replace(/^Module \d+ — /, "");
  const body = md.replace(/^# .+\n/, "");
  // Links to other handbook files become in-app anchors; links to repo files are shown as plain text.
  const html = marked.parse(body, { async: false }).replace(/<a href="(?!https?:)[^"]*">([^<]*)<\/a>/g, "<span>$1</span>");
  return { slug: f.replace(/\.md$/, ""), n: Number(f.slice(0, 2)), title, html };
});
const out = `/* Generated by scripts/build_handbook.mjs from docs/handbook/*.md. Do not edit. */\nexport const HANDBOOK: { slug: string; n: number; title: string; html: string }[] = ${JSON.stringify(modules, null, 1)};\n`;
writeFileSync("src/features/learn/handbook.generated.ts", out);
console.log(`handbook: ${modules.length} modules`);
