import type { StrategySpec, StrategyRule } from "./schema";

/**
 * The 20 strategies from Appendix A as seed specs (strategy-spec/1.1, source type "document").
 * They start as DRAFT / UNCONFIRMED. Win rates and R:R ranges are UNVERIFIED claims from an AI-generated
 * document; they are stored as creatorClaims only. Items the document did not state are INFERRED and
 * become questions in the Read-Back.
 */

type Cat = StrategyRule["category"];
type Obj = StrategyRule["objectivity"];
type Meas = StrategyRule["measurability"];
type R = [id: string, cat: Cat, dir: StrategyRule["direction"], text: string, obj: Obj, meas: Meas, question: string, inferred?: boolean];
type A = [issue: string, question: string, suggestedDefault?: string];

interface SeedInput {
  key: string;
  name: string;
  style: StrategySpec["strategy"]["style"];
  methodology: string[];
  instruments: string[];
  timeframes: string[];
  summary: string;
  objectivity: string;
  claims: string[];
  rules: R[];
  ambiguities?: A[];
  sessions?: { name: string; start: string; end: string; tz: string; dst?: string }[];
  indicators?: string[];
  mistakes?: [string, string][];
}

function seed(i: SeedInput): StrategySpec & { seedKey: string } {
  const rules: StrategyRule[] = i.rules.map(([id, category, direction, text, objectivity, measurability, q, inferred]) => ({
    id,
    category,
    direction,
    setupName: "Setup A",
    text,
    parameters: {},
    timestamp: "",
    source: inferred ? "INFERRED" : "STATED",
    objectivity,
    measurableVersionSuggestion: null,
    measurability,
    requiredData: measurability === "YES" ? ["trade history"] : measurability === "PARTIAL" ? ["OHLC market data"] : ["trader checklist"],
    checklistQuestion: q,
  }));
  return {
    seedKey: i.key,
    schemaVersion: "strategy-spec/1.1",
    generatedBy: "appendix-a-seed",
    source: {
      videos: [],
      documents: [
        {
          title: "Master AI Trading Agent System Prompt & 20-Strategy + 5-Risk Blueprint",
          author: "Founder's research document (generated with Google Gemini)",
          date: null,
          notes: `Appendix A, ${i.key}. Source objectivity rating (unverified): ${i.objectivity}.`,
        },
      ],
    },
    strategy: {
      name: i.name,
      aliases: [],
      summary: i.summary,
      style: i.style,
      methodology: i.methodology,
      instruments: i.instruments,
      timeframes: { bias: [], setup: i.timeframes, entry: i.timeframes.slice(0, 1) },
      typicalHoldingTime: null,
      typicalTradesPerDay: null,
    },
    terms: [],
    indicators: (i.indicators ?? []).map((name) => ({ name, settings: {}, purpose: "", timestamp: "", source: "STATED" as const })),
    sessions: (i.sessions ?? []).map((s) => ({
      name: s.name,
      startTime: s.start,
      endTime: s.end,
      timezoneAsStated: s.tz,
      utcStart: null,
      utcEnd: null,
      dstNote: s.dst ?? null,
      timestamp: "",
      source: "STATED" as const,
    })),
    rules,
    risk: { riskPerTradePercent: null, positionSizingMethod: null, maxTradesPerDay: null, dailyLossStop: null, maxConsecutiveLosses: null, minRiskReward: null, notes: "" },
    management: { takeProfitTargets: [], partialCloses: [], breakevenRule: null, trailingRule: null, timeExitRule: null },
    executionFlow: rules.map((r, idx) => ({ step: idx + 1, description: r.text, ruleIds: [r.id] })),
    examples: [],
    checklist: rules.map((r) => ({ ruleId: r.id, question: r.checklistQuestion })),
    mistakeTags: (i.mistakes ?? []).map(([tag, meaning]) => ({ tag, meaning })),
    creatorClaims: i.claims.map((claim) => ({ claim, timestamp: "", status: "UNVERIFIED" as const })),
    ambiguities: (i.ambiguities ?? []).map(([issue, q, def], idx) => ({
      id: `A${idx + 1}`,
      issue,
      whyItMatters: "",
      questionForTrader: q,
      suggestedDefault: def ?? null,
    })),
    analystNotes: [],
  };
}

